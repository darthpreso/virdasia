function render() {
  const app = document.querySelector("#app");
  // Mid email-confirmation return: we're about to route to shop once the session
  // settles, so render shop right away instead of flashing the home page.
  if (pendingAuthNext === "shop" || pendingRecovery || pendingAuthError) {
    app.innerHTML = shopPage();
    bindEvents();
    return;
  }
  if (state.route.startsWith("product/")) {
    app.innerHTML = productDetailPage();
    bindEvents();
    return;
  }

  const pages = {
    home: homePage,
    shop: shopPage,
    about: aboutPage,
    settings: settingsPage,
    cart: cartPage,
    checkout: checkoutPage,
    terms: () => legalPage("terms"),
    privacy: () => legalPage("privacy"),
    shipping: () => legalPage("shipping"),
    contact: contactPage,
    error: errorPage,
  };

  // A throw while building a page used to blank the screen entirely. Catching it
  // here means the visitor gets the error page with a way out instead.
  try {
    app.innerHTML = (pages[state.route] || errorPage)();
  } catch (error) {
    console.error("Render failed:", error);
    state.routeError = error?.message || "Unexpected error";
    try {
      app.innerHTML = errorPage();
    } catch (fallbackError) {
      console.error("Error page failed too:", fallbackError);
      app.innerHTML = `<main style="padding:80px 24px;text-align:center;font-family:Arial,sans-serif;">
        <h1>Something went wrong</h1>
        <p>Please <a href="#/home" onclick="location.reload()">reload the page</a> or email support@virdasia.com.</p>
      </main>`;
    }
  }
  bindEvents();
}

// After a successful Stripe checkout, Stripe redirects back with ?checkout=success.
// Captured from the URL at load, before Supabase consumes its auth params.
let pendingAuthNext = null;
// Set when the visitor arrives from a password-reset email. The recovery link
// signs them in, but the point is to choose a NEW password — so we hold this
// flag until the session lands, then open the "set a new password" modal.
let pendingRecovery = false;
// Set when an auth link came back with an error (expired, or already used).
// Held until the session resolves, because someone who already confirmed on an
// earlier link is signed in and needs reassurance, not a form.
let pendingAuthError = null;

// Once the session has settled after an auth return, send the visitor to shop.
function maybeRouteAfterAuth() {
  if (pendingAuthError) {
    if (!state.auth.ready) return; // wait until we know whether they're signed in
    const { recoveryFlow } = pendingAuthError;
    pendingAuthError = null;
    try { window.history.replaceState({}, "", window.location.pathname); } catch (e) { /* ignore */ }
    window.location.hash = "#/shop";

    // Clicking an older link after a newer one already worked is the common
    // case: they're signed in and nothing is wrong.
    // Setting the hash above queues a re-render that rebuilds the toast node,
    // so defer the message past it or it's wiped before anyone sees it.
    const notify = (message) => window.setTimeout(() => showToast(message), 450);

    if (state.auth.user) {
      render();
      notify("Already Confirmed — You're Signed In");
      return;
    }

    state.authModal = { mode: recoveryFlow ? "forgot" : "resend", email: "" };
    render();
    notify(recoveryFlow ? "That Reset Link Expired" : "That Link Expired Or Was Already Used");
    return;
  }

  if (pendingRecovery) {
    if (!state.auth.user) return; // wait for the recovery session to land
    pendingRecovery = false;
    try { window.history.replaceState({}, "", window.location.pathname); } catch (e) { /* ignore */ }
    state.authModal = { mode: "recovery" };
    window.location.hash = "#/shop";
    render();
    return;
  }
  if (pendingAuthNext !== "shop") return;
  pendingAuthNext = null;
  try { window.history.replaceState({}, "", window.location.pathname); } catch (e) { /* ignore */ }
  window.location.hash = "#/shop";
}

function handleCheckoutReturn() {
  const params = new URLSearchParams(window.location.search);
  if (params.get("checkout") === "success") {
    state.cart = [];
    writeJson("nebula-cart", state.cart);
    // The code is spent now; clearing it stops a stale discount showing on the
    // next order, where it would quote a total Stripe won't honour.
    state.discount = null;
    state.discountDraft = "";
    state.discountError = "";
    window.history.replaceState({}, "", window.location.pathname + window.location.hash);
    setTimeout(() => showToast("Payment received — thank you!"), 500);
    return;
  }
  // Email-confirmation return. Supabase may honor our ?next=shop flag, but if the
  // redirect fell back to the Site URL it still carries auth params (?code=... for
  // PKCE, or #access_token=... in the hash for implicit). Any of these means the
  // visitor just confirmed their email, so route them to the shop, not home.
  const href = window.location.href;

  // Failed auth return. Supabase reports expired/consumed links as error params
  // (in the hash for implicit flow). Without this the visitor would land on the
  // shop with no session and no explanation, waiting on a modal that never opens.
  const hashParams = new URLSearchParams(window.location.hash.replace(/^#\/?/, ""));
  const authError = hashParams.get("error_code") || hashParams.get("error") || params.get("error_code") || params.get("error");
  if (authError) {
    // The error itself doesn't say which flow it came from, but our own
    // ?next= flag survives on the redirect — so use that to decide whether to
    // offer a fresh reset link or a fresh confirmation email. Getting this
    // wrong shows a password-reset form to someone who clicked a stale signup
    // link, which is alarming and nonsensical.
    pendingAuthError = {
      recoveryFlow: params.get("next") === "recovery" || href.includes("type=recovery"),
    };
    return;
  }

  // Password-recovery return. Must be checked BEFORE the generic auth return
  // below: the link does sign the visitor in, but sending them straight to the
  // shop would leave their old password in place. Flag it instead so
  // maybeRouteAfterAuth() opens the "set a new password" modal.
  if (
    params.get("next") === "recovery" ||
    params.get("type") === "recovery" ||
    href.includes("type=recovery")
  ) {
    pendingRecovery = true;
    return;
  }
  if (
    params.get("next") === "shop" ||
    params.get("code") ||
    params.get("type") === "signup" ||
    href.includes("access_token=") ||
    href.includes("type=signup")
  ) {
    pendingAuthNext = "shop";
  }
}

window.addEventListener("hashchange", setRoute);
