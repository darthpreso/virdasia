function initSupabaseAuth() {
  const config = getSupabaseConfig();
  if (!config.url || !config.publishableKey) {
    state.auth.configured = false;
    state.auth.ready = true;
    state.auth.error = "Missing Supabase project URL or publishable key.";
    return;
  }

  if (!window.supabase?.createClient) {
    state.auth.configured = false;
    state.auth.ready = true;
    state.auth.error = "Supabase browser client did not load.";
    return;
  }

  state.auth.configured = true;
  state.auth.client = window.supabase.createClient(config.url, config.publishableKey, {
    auth: {
      persistSession: true,
      autoRefreshToken: true,
      detectSessionInUrl: true,
    },
  });

  loadWaitlistCounts().then(render).catch(() => {});

  state.auth.client.auth.onAuthStateChange((event, session) => {
    // Supabase fires this when a recovery link is consumed; belt-and-suspenders
    // alongside the URL sniffing in handleCheckoutReturn().
    if (event === "PASSWORD_RECOVERY") pendingRecovery = true;
    state.auth.session = session;
    state.auth.user = session?.user || null;
    state.auth.ready = true;
    // Close the auth modal once signed in — but only the modes whose whole
    // purpose was getting you signed in. Recovery needs the session to land
    // before its form is usable, and the "sent"/"password" screens report a
    // completed action the visitor should dismiss themselves. updateUser and
    // signInWithPassword both fire this listener, so without the allow-list a
    // success screen would be wiped the instant it appeared.
    if (state.auth.user && AUTH_MODES_DISMISS_ON_SIGNIN.includes(state.authModal?.mode)) {
      state.authModal = null;
    }
    syncAuthProfile();
    render();
    refreshWaitlist();
    maybeRouteAfterAuth();
  });

  state.auth.client.auth.getSession().then(({ data, error }) => {
    if (error) state.auth.error = error.message;
    state.auth.session = data?.session || null;
    state.auth.user = data?.session?.user || null;
    state.auth.ready = true;
    syncAuthProfile();
    render();
    refreshWaitlist();
    maybeRouteAfterAuth();
  }).catch((error) => {
    state.auth.error = error.message || "Unable to load Supabase session.";
    state.auth.ready = true;
    render();
    maybeRouteAfterAuth();
  });

  // Safety net: if an auth return never resolves through the callbacks above
  // (e.g. some implicit-flow edge cases), still send the visitor to the shop.
  if (pendingAuthNext === "shop" || pendingRecovery || pendingAuthError) window.setTimeout(maybeRouteAfterAuth, 3500);
}

function formValue(selector) {
  return document.querySelector(selector)?.value.trim() || "";
}

async function handleAuthAction(action) {
  if (!state.auth.client) {
    showToast("Supabase Not Configured");
    return;
  }

  const name = formValue("#name");
  const email = formValue("#email");
  const password = document.querySelector("#password")?.value || "";
  // Use a query flag (not a hash route) so Supabase's appended auth tokens don't
  // clobber the destination. The app reads ?next=shop after the session lands.
  const redirectTo = `${window.location.origin}${window.location.pathname}?next=shop`;

  try {
    if (action === "sign-up") {
      if (!email || !password) {
        showToast("Email And Password Required");
        return;
      }
      const { error } = await state.auth.client.auth.signUp({
        email,
        password,
        options: {
          data: { display_name: name },
          emailRedirectTo: redirectTo,
        },
      });
      if (error) throw error;
      // Hold the modal open on a confirmation screen rather than closing it — a
      // toast vanishes in under two seconds, which is easy to miss right after
      // submitting, leaving people unsure whether the account was created.
      state.waitlistModal = null;
      state.authModal = { mode: "sent", kind: "signup", email, cooldownUntil: Date.now() + AUTH_RESEND_COOLDOWN_SECONDS * 1000 };
      render();
    }

    if (action === "sign-in") {
      if (!email || !password) {
        showToast("Email And Password Required");
        return;
      }
      const { error } = await state.auth.client.auth.signInWithPassword({ email, password });
      if (error) throw error;
      showToast("Signed In");
    }

    if (action === "sign-out") {
      const { error } = await state.auth.client.auth.signOut();
      if (error) throw error;
      state.authModal = null; // also dismisses the recovery modal's "sign out" escape
      render();
      showToast("Signed Out");
    }

    if (action === "reset-password") {
      if (!email) {
        showToast("Email Required");
        return;
      }
      // Supabase appends its own recovery params; ?next=recovery survives them and
      // is what handleCheckoutReturn() looks for on the way back in.
      const { error } = await state.auth.client.auth.resetPasswordForEmail(email, {
        redirectTo: `${window.location.origin}${window.location.pathname}?next=recovery`,
      });
      if (error) throw error;
      state.authModal = { mode: "sent", kind: "reset", email, cooldownUntil: Date.now() + AUTH_RESEND_COOLDOWN_SECONDS * 1000 };
      render();
    }

    // Escape hatch for someone who can't complete the change because they don't
    // remember the current password: drop the session and use the email flow.
    if (action === "sign-out-reset") {
      const known = state.auth.user?.email || "";
      await state.auth.client.auth.signOut().catch(() => {});
      state.authModal = { mode: "forgot", email: known };
      render();
      return;
    }

    if (action === "resend-confirmation") {
      if (!email) {
        showToast("Email Required");
        return;
      }
      const { error } = await state.auth.client.auth.resend({
        type: "signup",
        email,
        options: { emailRedirectTo: redirectTo },
      });
      if (error) throw error;
      state.authModal = { mode: "sent", kind: "resend", email, cooldownUntil: Date.now() + AUTH_RESEND_COOLDOWN_SECONDS * 1000 };
      render();
    }

    if (action === "set-password") {
      const confirmPassword = document.querySelector("#password-confirm")?.value || "";
      if (password.length < 6) {
        showToast("Password Must Be 6+ Characters");
        return;
      }
      if (password !== confirmPassword) {
        showToast("Passwords Do Not Match");
        return;
      }
      const { error } = await state.auth.client.auth.updateUser({ password });
      if (error) throw error;
      state.authModal = { mode: "sent", kind: "passwordChanged", email: "" };
      render();
    }

    if (action === "update-profile") {
      const updates = { data: { display_name: name } };
      if (email && email !== state.auth.user?.email) updates.email = email;
      if (password) updates.password = password;
      const { error } = await state.auth.client.auth.updateUser(updates);
      if (error) throw error;
      state.settings.name = name;
      state.settings.email = email;
      saveSettings();
      showToast("Account Saved");
    }
  } catch (error) {
    const message = error.message || "Auth Error";
    // Supabase rejects emails sent inside its minimum interval with the exact
    // number of seconds left. Trust that over our local guess and restart the
    // countdown from it, so the UI can't drift out of sync with the setting.
    const wait = /after (\d+) seconds?/i.exec(message);
    if (wait && state.authModal) {
      const seconds = Number(wait[1]) + 1;
      state.authModal.cooldownUntil = Date.now() + seconds * 1000;
      if (state.authModal.mode !== "sent") state.authModal.mode = "sent";
      render();
      showToast(`Please Wait ${seconds}s Before Trying Again`);
      return;
    }
    showToast(message);
  }
}

// Settings → Change Password. Separate from the recovery modal because the
// visitor is already signed in; Supabase accepts the update on the live session.
async function handlePasswordChange() {
  if (!state.auth.client) {
    showToast("Supabase Not Configured");
    return;
  }
  const current = document.querySelector("#current-password")?.value || "";
  const next = document.querySelector("#new-password")?.value || "";
  const confirmNext = document.querySelector("#new-password-confirm")?.value || "";
  const email = state.auth.user?.email || "";

  // Errors render inside the modal so they sit next to the fields they describe
  // and stay on screen until resolved.
  const fail = (message) => {
    if (state.authModal) state.authModal.error = message;
    render();
  };

  if (!current) return fail("Enter your current password.");
  if (next.length < 6) return fail("Your new password must be at least 6 characters.");
  if (next !== confirmNext) return fail("The new passwords don't match.");
  if (next === current) return fail("Your new password must be different from your current one.");
  if (!email) return fail("Your session has expired. Please sign in again.");

  const button = document.querySelector("[data-auth-form] .primary-button");
  if (button) {
    button.disabled = true;
    button.textContent = "Saving…";
  }

  try {
    // Supabase lets a live session change its own password without proof, so
    // verify the old one first by re-authenticating. Otherwise anyone who finds
    // an unlocked device could lock the owner out of their account.
    const { error: reauthError } = await state.auth.client.auth.signInWithPassword({ email, password: current });
    if (reauthError) {
      fail("That current password is incorrect.");
      return;
    }

    const { error } = await state.auth.client.auth.updateUser({ password: next });
    if (error) {
      // Supabase rejects a no-op change server-side too; say so plainly rather
      // than passing its wording straight through.
      const same = /should be different|different from the old/i.test(error.message || "");
      fail(same ? "Your new password must be different from your current one." : (error.message || "Could not update your password."));
      return;
    }

    state.authModal = { mode: "sent", kind: "passwordChanged", email: "" };
    render();
  } catch (error) {
    fail(error.message || "Could not update your password.");
  } finally {
    const liveButton = document.querySelector("[data-auth-form] .primary-button");
    if (liveButton && liveButton.textContent === "Saving…") {
      liveButton.disabled = false;
      liveButton.textContent = "Save Password";
    }
  }
}

// Settings → Delete my account. The password re-check happens server-side in the
// delete-account edge function, so a left-open session alone can't wipe an account.
async function handleAccountDelete() {
  const password = document.querySelector("#delete-password")?.value || "";
  if (!password) {
    showToast("Password Required");
    return;
  }
  const token = state.auth.session?.access_token;
  if (!token) {
    showToast("Please Sign In Again");
    return;
  }

  const button = document.querySelector("[data-delete-form] .danger-button");
  if (button) {
    button.disabled = true;
    button.textContent = "Deleting…";
  }

  try {
    const response = await fetch(`${window.NEBULA_SUPABASE_CONFIG.url}/functions/v1/delete-account`, {
      method: "POST",
      headers: { "content-type": "application/json", Authorization: `Bearer ${token}` },
      body: JSON.stringify({ password }),
    });
    const result = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(result.error || "Could not delete your account.");

    // Clear local traces too — the server no longer knows this person.
    await state.auth.client.auth.signOut().catch(() => {});
    state.deleteConfirming = false;
    state.waitlist = [];
    state.orders = [];
    state.authModal = { mode: "sent", kind: "accountDeleted", email: "" };
    render();
  } catch (error) {
    if (button) {
      button.disabled = false;
      button.textContent = "Permanently Delete Account";
    }
    showToast(error.message || "Could Not Delete Account");
  }
}

